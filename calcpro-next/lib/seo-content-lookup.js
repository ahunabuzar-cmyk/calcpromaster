// ====== SEO content lookup (server-only) ======
// Reads the shared js/seo-content.js (1.3 MB, 444 tools). Importing this module
// pulls the whole dataset into the SERVER bundle only — never the client — so
// page metadata + article rendering get full content without bloating first-load JS.
//
// `howtoSteps` are synthesized from the tool's input schema (server-safe: input
// labels are developer-authored). Tools WITHOUT pre-written SEO content get a
// programmatic fallback article so every tool page still ranks.

import { TOOL_SEO } from '@calcpro-js/seo-content.js';
// Unique per-tool ~100-word intro paragraphs (js/tool-intros.js, generated by
// generate-intros.js at the project root). Default import = the UMD
// module.exports object, so this resolves under both webpack (Next) and Node
// CJS-interop. Every one of the 548 tools gets its own unique intro so Google
// never flags thin/duplicate content.
import TOOL_INTROS from '@calcpro-js/tool-intros.js';
// Premium flagship content (js/seo-premium.js): hand-written 30-section articles
// for the highest-value tools, composed server-side by the shared compositor so
// vanilla and Next render identical markup. Falls back to TOOL_SEO everywhere else.
import SEO_PREMIUM from '@calcpro-js/seo-premium.js';

// Cache the fallback builders per key so repeated SSR calls stay cheap.
const fallbackCache = new Map();

function buildFallback(tool) {
  if (!tool) return null;
  const name = tool.name || tool.id;
  const desc = tool.desc || `Free ${name} calculator. Instant results, no sign-up.`;
  const kw = String(tool.kw || '').split(',').map((s) => s.trim()).filter(Boolean);
  const inputs = Array.isArray(tool.inputs) ? tool.inputs : [];

  const howtoSteps = inputs.map((inp) => {
    const label = inp.label || inp.id;
    if (inp.type === 'select') {
      const opts = (inp.opts || []).map((o) => o.l).join(', ');
      return `Choose ${label}${opts ? ` (${opts})` : ''}.`;
    }
    if (inp.type === 'checkbox') return `Tick ${label} if it applies.`;
    return `Enter ${label} — the main numeric value for this calculation. Adjust as needed and see the result change.`;
  });
  howtoSteps.push('Review the result — the answer appears instantly, with a step-by-step breakdown to verify the math.');

  const faqs = [
    { q: `Is this ${name} really free?`, a: 'Yes. No hidden charges, no premium tiers, no usage limits. Every calculator on CalcPro is free forever.' },
    { q: 'Does it work offline?', a: 'After the first visit, the tool caches locally and works without an internet connection.' },
    { q: 'Do you save my data?', a: 'No. Everything runs in your browser. Your inputs never reach a server.' },
    { q: 'Do I need to create an account?', a: 'No account required. Open the page and use it immediately.' },
  ];

  const descHtml = [
    `<h2>What This Calculator Does</h2>`,
    `<p>${name} solves a specific problem: ${desc}. Instead of reaching for a spreadsheet or doing mental math, you get an instant answer. The calculation runs locally — nothing leaves your browser. No uploads, no accounts.</p>`,
    `<h2>How to Use It</h2>`,
    `<ol>${howtoSteps.map((s) => `<li>${s}</li>`).join('')}</ol>`,
    `<h2>Why It Works</h2>`,
    `<p>Every result uses a standard, verified formula. Change any input and the result recalculates instantly, so you can compare scenarios side by side and see exactly how each factor changes the outcome.</p>`,
    `<h2>Key Advantages</h2>`,
    `<ul><li><strong>100% free</strong> — no premium features locked away.</li><li><strong>Client-side only</strong> — your data stays on your device.</li><li><strong>Instant recalc</strong> — change any input, the result updates immediately.</li><li><strong>Step-by-step breakdown</strong> — see how the answer was derived.</li></ul>`,
    `<h2>Who Uses This Tool</h2>`,
    `<p>Students use ${name} to check homework and understand how inputs affect outcomes. Professionals rely on it for quick estimates during meetings. Everyday users plug in their own numbers to plan and compare. It is part of CalcPro — ${kw.length ? kw.join(', ') : 'one of 566+ free calculators'} — all running in your browser with no tracking.</p>`,
  ].join('\n');

  return {
    title: `${name} — Free Online Calculator`,
    metaDesc: `${name}: ${desc} Free, instant, no sign-up.`,
    desc: descHtml,
    faqs,
    howtoSteps,
    intro: (TOOL_INTROS && TOOL_INTROS[toolId]) || '',
  };
}

export function getToolSeo(toolId) {
  // PREMIUM tier first: full Master-Blueprint article for flagship tools.
  const premium = SEO_PREMIUM && SEO_PREMIUM[toolId];
  if (premium) {
    const composed = typeof SEO_PREMIUM.composeArticle === 'function'
      ? SEO_PREMIUM.composeArticle(premium)
      : (premium.intro || '');
    return {
      title: premium.seoTitle || premium.h1 || toolId,
      metaDesc: premium.metaDesc || '',
      desc: composed,
      faqs: Array.isArray(premium.faqs) ? premium.faqs : [],
      howtoSteps: (premium.howToUse || '').split(/<li>/).slice(1).map((s) => s.replace(/<\/li>.*/s, '').replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim()).filter(Boolean),
      intro: premium.h1 || (TOOL_INTROS && TOOL_INTROS[toolId]) || '',
    };
  }
  const pre = TOOL_SEO && TOOL_SEO[toolId];
  if (pre) {
    // Normalize: guarantee howtoSteps exists for the HowTo schema
    return {
      title: pre.title || toolId,
      metaDesc: pre.metaDesc || '',
      desc: pre.desc || '',
      faqs: Array.isArray(pre.faqs) ? pre.faqs : [],
      howtoSteps: pre.howtoSteps || [],
      intro: (TOOL_INTROS && TOOL_INTROS[toolId]) || '',
    };
  }
  // Fallback path — build from the tool schema (handled by the caller via getTool)
  return null;
}

export function getToolSeoWithFallback(toolId, tool) {
  const fromSeo = getToolSeo(toolId);
  if (fromSeo) return fromSeo;
  if (!fallbackCache.has(toolId)) fallbackCache.set(toolId, buildFallback(tool));
  return fallbackCache.get(toolId);
}
