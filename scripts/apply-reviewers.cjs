#!/usr/bin/env node
/* ============================================================
 * apply-reviewers.cjs — sync owner-provided reviewer bylines
 * ------------------------------------------------------------
 * Reads data/reviewers.json (owner-editable) and writes
 * js/reviewers-data.js, which js/category-methodology.js reads in
 * BOTH Node (SSG) and the browser. This keeps real names OUT of
 * source code so the owner only edits the JSON.
 *
 * data/reviewers.json shape (every field optional per category):
 * {
 *   "_default": { "name": "Jane Doe", "credentials": "CFP", "url": "/about" },
 *   "finance":   { "name": "Jane Doe", "credentials": "CFP", "url": "/about" }
 * }
 *
 * Empty {} => NO bylines are shown. We never invent reviewer names.
 *
 * Run: node scripts/apply-reviewers.cjs   (also wired into build-deploy.js)
 * ============================================================ */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

function loadJson() {
  const p = path.join(ROOT, 'data', 'reviewers.json');
  if (!fs.existsSync(p)) return {};
  const raw = fs.readFileSync(p, 'utf8').trim();
  if (!raw) return {};
  const obj = JSON.parse(raw);
  if (!obj || typeof obj !== 'object' || Array.isArray(obj)) {
    throw new Error('data/reviewers.json must be a JSON object');
  }
  return obj;
}

// Keep only entries with a real, non-empty name. `_comment` and friends are
// ignored (they are documentation, not reviewers).
function normalize(raw) {
  const out = {};
  const warnings = [];
  for (const [key, val] of Object.entries(raw)) {
    if (key.charAt(0) === '_' && key !== '_default') continue; // docs/comment keys
    if (val === null || val === undefined) continue;
    if (typeof val !== 'object') { warnings.push('skip "' + key + '": not an object'); continue; }
    const name = typeof val.name === 'string' ? val.name.trim() : '';
    if (!name) { warnings.push('skip "' + key + '": no non-empty "name" (bylines need a real person)'); continue; }
    const entry = { name };
    if (typeof val.credentials === 'string' && val.credentials.trim()) entry.credentials = val.credentials.trim();
    if (typeof val.url === 'string' && val.url.trim().charAt(0) === '/') entry.url = val.url.trim();
    out[key] = entry;
  }
  return { out, warnings };
}

function buildModule(obj) {
  return '/* GENERATED by scripts/apply-reviewers.cjs from data/reviewers.json — DO NOT EDIT BY HAND.\n' +
    ' * Owner-editable source: data/reviewers.json\n' +
    ' * Empty map = no reviewer bylines shown (we never invent reviewer names). */\n' +
    '(function (root) {\n' +
    '  var R = ' + JSON.stringify(obj, null, 2) + ';\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = R;\n" +
    "  if (typeof window !== 'undefined') window.__CPM_REVIEWERS__ = R;\n" +
    "})(typeof window !== 'undefined' ? window : globalThis);\n";
}

function run() {
  let raw;
  try {
    raw = loadJson();
  } catch (e) {
    console.error('reviewers: ' + e.message + ' — writing empty map (no bylines)');
    raw = {};
  }
  const { out, warnings } = normalize(raw);
  warnings.forEach(w => console.warn('  ! ' + w));
  fs.writeFileSync(path.join(ROOT, 'js', 'reviewers-data.js'), buildModule(out));
  const keys = Object.keys(out);
  console.log('reviewers: ' + keys.length + ' configured' +
    (keys.length ? ' (' + keys.join(', ') + ')' : ' — no bylines shown'));
}

if (require.main === module) run();

module.exports = { run, loadJson, normalize, buildModule };
