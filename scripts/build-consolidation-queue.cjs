#!/usr/bin/env node
// ============================================================
// CalcProMaster — duplicate-URL consolidation queue
// ------------------------------------------------------------
// Jab ek path do URLs par impressions le raha ho (/x aur /x/), Google ko batana
// padta hai ki kaunsa URL asli hai. Redirect + sitemap + canonical tag ye kaam
// khud karte hain, lekin sirf RECRAWL par — aur recrawl trigger karne ka koi
// public API nahi hai (GSC ka "Request indexing" UI-only hai).
//
// Ye script GSC page export se twins nikaal ke ek queue banati hai: har path ka
// CANONICAL URL (jo 200 deta hai) + us path ke dono forms ki impressions, taaki
// owner sirf canonical URL GSC me submit kare — twin form kabhi nahi.
//
// Input:  data/gsc-page-impressions.json  (npm run gsc:pages)
// Output: docs/CONSOLIDATION-QUEUE.md
// Usage:  node scripts/build-consolidation-queue.cjs [--top 100]
// ============================================================
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://calcpromaster.com';
// `--input <file>` points at a fresher GSC page export, so the queue can be
// rebuilt from the window the owner is actually looking at.
const inputArg = (() => {
  const i = process.argv.indexOf('--input');
  return i >= 0 && process.argv[i + 1] ? path.resolve(process.argv[i + 1]) : null;
})();
const INPUT = inputArg || path.join(ROOT, 'data', 'gsc-page-impressions.json');
const OUT = path.join(ROOT, 'docs', 'CONSOLIDATION-QUEUE.md');

const topArg = (() => {
  const i = process.argv.indexOf('--top');
  const v = i >= 0 ? parseInt(process.argv[i + 1], 10) : NaN;
  return Number.isFinite(v) && v > 0 ? v : 100;
})();

/**
 * Group page URLs by path (slash-insensitive) and return only the paths that
 * appear in more than one URL form — the split-signal rows.
 * Pure: takes the `pages` map straight from the GSC export.
 */
function findTwinPaths(pages) {
  const groups = new Map();
  for (const [url, m] of Object.entries(pages || {})) {
    let p;
    try { p = new URL(url, SITE).pathname } catch (e) { continue; }
    const key = p.replace(/\/+$/, '') || '/';
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push({
      url,
      path: p,
      impressions: m.impressions || 0,
      clicks: m.clicks || 0,
      position: m.position || null,
    });
  }
  const twins = [];
  for (const [key, rows] of groups) {
    if (rows.length < 2) continue;
    const impressions = rows.reduce((s, r) => s + r.impressions, 0);
    const clicks = rows.reduce((s, r) => s + r.clicks, 0);
    twins.push({ path: key, rows, impressions, clicks });
  }
  return twins.sort((a, b) => b.impressions - a.impressions);
}

/** The form that serves 200: directory pages keep the slash, flat pages do not. */
function canonicalUrlFor(p, exists) {
  const clean = p.replace(/\/+$/, '');
  if (!clean) return SITE + '/';
  if (exists) {
    // deploy files are keyed without a leading slash ('health/x/index.html').
    const key = clean.replace(/^\//, '');
    if (exists.has(key + '/index.html')) return SITE + clean + '/';
    if (exists.has(key + '.html')) return SITE + clean;
  }
  return SITE + p;
}

function deployFiles() {
  const set = new Set();
  const dir = path.join(ROOT, 'deploy');
  if (!fs.existsSync(dir)) return null;
  (function walk(d, base) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const rel = base ? base + '/' + e.name : e.name;
      if (e.isDirectory()) walk(path.join(d, e.name), rel);
      else set.add(rel);
    }
  })(dir, '');
  return set;
}

function main() {
  if (!fs.existsSync(INPUT)) {
    console.error('  ✗ ' + path.relative(ROOT, INPUT) + ' missing — run `npm run gsc:pages` first');
    process.exit(1);
  }
  const data = JSON.parse(fs.readFileSync(INPUT, 'utf8'));
  const twins = findTwinPaths(data.pages);
  const files = deployFiles();
  const queue = twins.slice(0, topArg).map((t) => ({ ...t, canonical: canonicalUrlFor(t.path, files) }));

  const splitImpressions = twins.reduce((s, t) => s + t.impressions, 0);
  const lines = [];
  lines.push('# Duplicate-URL consolidation queue');
  lines.push('');
  lines.push('Generated by `npm run seo:consolidation-queue` from `data/gsc-page-impressions.json`');
  lines.push('(window ' + (data.startDate || '?') + ' → ' + (data.endDate || '?') + ', generated ' + new Date().toISOString().slice(0, 10) + ').');
  lines.push('');
  lines.push('**' + twins.length + ' paths carry two URL forms**, holding **' + splitImpressions.toLocaleString('en-US') + ' impressions** between them.');
  if (!twins.length) {
    lines.push('');
    lines.push('> This export contains no twin paths. The slash twins have redirected since 2026-10-21, so');
    lines.push('> a window that ends before a full recrawl shows none. Re-run against a newer export:');
    lines.push('> `node scripts/build-consolidation-queue.cjs --input <gsc-pages-export.json>`.');
  }
  lines.push('Submit **only the canonical URL** below in GSC → URL Inspection → Request indexing.');
  lines.push('Never submit the twin form: it 308s, and resubmitting it re-splits the signal.');
  lines.push('');
  lines.push('| # | Path | Canonical URL (submit this) | Twin impressions | Clicks |');
  lines.push('| --- | --- | --- | --- | --- |');
  queue.forEach((t, i) => {
    lines.push('| ' + (i + 1) + ' | `' + t.path + '` | ' + t.canonical + ' | ' + t.impressions + ' | ' + t.clicks + ' |');
  });
  lines.push('');
  lines.push('## Why this works');
  lines.push('');
  lines.push('1. The twin 308s to the canonical URL (verified live: 1419/1419 sitemap twins).');
  lines.push('2. `sitemap.xml` lists only the canonical URL, and every canonical tag self-references it.');
  lines.push('3. A recrawl of the canonical URL lets Google drop the twin row and merge the impressions.');
  lines.push('');
  lines.push('Gate: `npm run seo:hosts` fails if a twin ever answers 200 again; `npm run check:canonical-urls`');
  lines.push('fails if the built tree or the sitemap re-creates a second form.');

  fs.writeFileSync(OUT, lines.join('\n') + '\n');
  console.log('input: ' + path.relative(ROOT, INPUT) + ' (' + Object.keys(data.pages || {}).length + ' page rows)');
  console.log('consolidation queue: ' + twins.length + ' duplicated paths (' + splitImpressions.toLocaleString('en-US') + ' impressions)');
  console.log('  wrote ' + path.relative(ROOT, OUT) + ' with the top ' + queue.length + ' canonical URLs');
  if (!twins.length) {
    console.log('\n  ℹ️  This export has no twin paths. The redirects have been live since');
    console.log('     2026-10-21, so a window ending before a full recrawl will show none.');
    console.log('     For a newer window: GSC → Pages → Export, then');
    console.log('     node scripts/build-consolidation-queue.cjs --input <export.json>');
  }
}

if (require.main === module) {
  try { main(); } catch (e) { console.error('build-consolidation-queue crashed: ' + (e && e.message)); process.exit(1); }
}

module.exports = { findTwinPaths, canonicalUrlFor };
