#!/usr/bin/env node
// ============================================================
// CalcProMaster — Not-indexed URL action plan builder
//
// Reads the aggregated GSC coverage snapshot (data/gsc-coverage-report.json)
// and the latest query/page export (data/gsc-queries-raw.txt), then writes a
// prioritised, white-hat action plan to docs/NOT-INDEXED-ACTION-PLAN.md.
//
// Priority = category demand weight + a boost for pages that already earn
// impressions (those slipped into the index since the snapshot).
//
// Usage: node scripts/build-not-indexed-plan.cjs
// ============================================================
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const rep = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'gsc-coverage-report.json'), 'utf8'));

const notIndexed = [...(rep.lists.DISCOVERED || []), ...(rep.lists.UNKNOWN || [])];

// pages currently earning impressions (from the page-level export)
const impressions = new Map();
const raw = fs.readFileSync(path.join(ROOT, 'data', 'gsc-queries-raw.txt'), 'utf8');
for (const line of raw.split('\n')) {
  const m = line.match(/^(https:\/\/calcpromaster\.com\/\S*)\s+clicks=(\d+)\s+impr=(\d+)\s+ctr=([\d.]+)%\s+pos=([\d.]+)/);
  if (m) impressions.set(m[1].replace(/\/$/, ''), { clicks: +m[2], impr: +m[3], ctr: +m[4], pos: +m[5] });
}
const norm = u => ('https://calcpromaster.com' + u).replace(/\/$/, '');

// category demand weights (search volume proxy: finance/math/health convert and
// search most; niche categories later)
const CAT_WEIGHT = {
  finance: 10, math: 9, health: 9, career: 7, business: 7, fitness: 6,
  education: 6, conversion: 6, auto: 6, construction: 5, science: 5,
  food: 5, family: 5, tech: 5, utilities: 4, homegarden: 4, lifestyle: 4,
  everyday: 3, engineering: 3, regional: 8, guides: 6,
};
const catOf = u => u.split('/').filter(Boolean)[0] || '(root)';

const rows = notIndexed.map(x => {
  const c = catOf(x.url);
  const nowImpr = impressions.has(norm(x.url));
  const impr = nowImpr ? impressions.get(norm(x.url)).impr : 0;
  const score = (CAT_WEIGHT[c] || 3) + (nowImpr ? 25 + impr : 0);
  return { url: x.url, coverage: x.coverage, cat: c, impr, score };
}).sort((a, b) => b.score - a.score);

const stillNotIndexed = rows.filter(r => r.impr === 0);
const slipped = rows.filter(r => r.impr > 0);

// category tally for still-not-indexed
const byCat = {};
for (const r of stillNotIndexed) byCat[r.cat] = (byCat[r.cat] || 0) + 1;
const catList = Object.entries(byCat).sort((a, b) => b[1] - a[1]);

// sitemap freshness: count total
const sitemap = fs.readFileSync(path.join(ROOT, 'deploy', 'sitemap.xml'), 'utf8');
const sitemapCount = [...sitemap.matchAll(/<loc>/g)].length;

const batchList = rep.batches.map(b => b.name).join(', ');

let md = '# NOT-INDEXED ACTION PLAN — calcpromaster.com\n\n';
md += '> Auto-generated by `node scripts/build-not-indexed-plan.cjs` from real GSC data.\n';
md += '> Coverage snapshot: ' + rep.ranAt.slice(0, 10) + ' (batches: ' + batchList + ').\n\n';

md += '## The numbers\n\n';
md += '| Metric | Value |\n|---|---|\n';
md += '| Coverage URLs inspected | ' + rep.uniqueUrls + ' |\n';
md += '| Indexed | ' + (rep.lists.INDEXED || []).length + ' |\n';
md += '| Not indexed (Discovered + Unknown) | ' + notIndexed.length + ' |\n';
md += '| …now earning impressions (slipped in since snapshot) | ' + slipped.length + ' |\n';
md += '| …still not indexed | ' + stillNotIndexed.length + ' |\n';
md += '| Sitemap URLs | ' + sitemapCount + ' |\n\n';

md += '## Root cause\n\n';
md += 'The domain is roughly two weeks old. Google throttles crawl and indexing for new sites: it\n';
md += 'discovers a URL, then decides whether the site as a whole is worth spending index budget on.\n';
md += 'This is normal and temporary. The fix is not "more pages" — it is **proving value on the\n';
md += 'pages Google already knows**, then letting crawl demand grow. Every lever below is white-hat.\n\n';

md += '## What is already healthy (do not re-do)\n\n';
md += '- Sitemap: ' + sitemapCount + ' URLs, **0 noindex** entries (no crawl-budget waste).\n';
md += '- Contextual internal links: every tool page has **≥3** editorial inlinks (see `docs/INTERNAL-LINK-AUDIT.md`).\n';
md += '- Prerendered HTML, correct canonicals, robots allow, trailing-slash 301, quality gate PASS.\n';
md += '- Freshness: review dates stamped on every page.\n\n';

md += '## Levers, in priority order\n\n';
md += '### L1 — Request Indexing (user, GSC) — highest immediate impact\n\n';
md += 'Google crawls what it is asked to crawl. Request indexing for the **top 40** pages below,\n';
md += 'about **12 per day** (GSC caps the daily quota). Start with the finance/math/health rows:\n';
md += 'they earn the most impressions per indexed page, so they compound fastest.\n\n';

md += '### L2 — Link from pages Google already trusts\n\n';
md += 'Add contextual links **from pages that already have impressions** to the not-indexed pages\n';
md += 'below. Google follows authority; a link from an indexed page is a crawl hint with weight.\n';
md += 'Target: the top 5 pages by impressions should each link to 3–5 not-indexed pages in the\n';
md += 'same intent. (The link-graph audit confirms there is room to add these without breaking the\n';
md += '3-inlink floor.)\n\n';

md += '### L3 — Deepen the not-indexed pages themselves\n\n';
md += 'A page that offers nothing beyond the calculator stays "Discovered". The 36 enhanced pages\n';
md += '(`js/tool-enhance.js`) show the pattern: a real formula, a verified data table, and internal\n';
md += 'links. Extend the same treatment to the next tier of not-indexed pages in finance and math.\n\n';

md += '### L4 — Authority signals (backlinks + brand)\n\n';
md += 'New-site trust is mostly external. The live backlinks (~14) plus the GitHub Pages reference\n';
md += 'pages and the outreach drafts in `docs/` move this. Each real dofollow link to a money page\n';
md += 'raises the whole site\u2019s crawl appetite.\n\n';

md += '### L5 — Re-pull coverage weekly\n\n';
md += 'The snapshot above is from ' + rep.ranAt.slice(0, 10) + '. Re-run the GSC inspection batches\n';
md += 'every Monday and re-run this script; the "slipped in" column is the real progress meter.\n\n';

md += '## Priority list — still not indexed (' + stillNotIndexed.length + ')\n\n';
md += 'Ranked by category demand + any impressions already earned.\n\n';
md += '| # | URL | Category | Coverage state |\n|---|---|---|---|\n';
for (let i = 0; i < Math.min(60, stillNotIndexed.length); i++) {
  const r = stillNotIndexed[i];
  md += '| ' + (i + 1) + ' | `' + r.url + '` | ' + r.cat + ' | ' + r.coverage + ' |\n';
}
if (stillNotIndexed.length > 60) md += '\n_…and ' + (stillNotIndexed.length - 60) + ' more (see `data/not-indexed-plan.json`)._\n';

md += '\n## By category (still not indexed)\n\n| Category | Count |\n|---|---|\n';
for (const [c, n] of catList) md += '| ' + c + ' | ' + n + ' |\n';

md += '\n## Slipped in since snapshot (' + slipped.length + ') — proof the levers work\n\n';
md += '| URL | Impressions |\n|---|---|\n';
for (const r of slipped.slice(0, 25)) md += '| `' + r.url + '` | ' + r.impr + ' |\n';

md += '\nFull machine-readable data: `data/not-indexed-plan.json`.\n';

fs.writeFileSync(path.join(ROOT, 'docs', 'NOT-INDEXED-ACTION-PLAN.md'), md);
fs.writeFileSync(path.join(ROOT, 'data', 'not-indexed-plan.json'), JSON.stringify({
  ranAt: new Date().toISOString(),
  snapshotRanAt: rep.ranAt,
  total: notIndexed.length,
  slipped: slipped.length,
  stillNotIndexed: stillNotIndexed.length,
  byCategory: byCat,
  priority: rows,
}, null, 2));

console.log('=== Not-indexed action plan ===');
console.log('snapshot: ' + rep.ranAt.slice(0, 10));
console.log('not indexed: ' + notIndexed.length + '  (slipped in: ' + slipped.length + ', still out: ' + stillNotIndexed.length + ')');
console.log('top categories: ' + catList.slice(0, 8).map(([c, n]) => c + ':' + n).join(' '));
console.log('\n💾 docs/NOT-INDEXED-ACTION-PLAN.md + data/not-indexed-plan.json');
