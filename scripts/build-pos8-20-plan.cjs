#!/usr/bin/env node
// ============================================================
// CalcProMaster — "Position 8–20 → top 5" opportunity plan
// ------------------------------------------------------------
// 8–20 position wale pages sabse sasta win hain: Google already unhe page
// 2 par rank kar raha hai, sirf on-page + CTR + authority thoda aur chahiye.
//
// Input:  data/gsc-page-impressions.json (per-page pos/impressions/clicks)
// Output: docs/POS-8-20-PLAN.md  ·  data/pos-8-20-plan.json
// Usage:  node scripts/build-pos8-20-plan.cjs [--min-impr 1]
// ============================================================
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://calcpromaster.com';
const IMP = path.join(ROOT, 'data', 'gsc-page-impressions.json');
const OUT_MD = path.join(ROOT, 'docs', 'POS-8-20-PLAN.md');
const OUT_JSON = path.join(ROOT, 'data', 'pos-8-20-plan.json');

const argVal = (n, d) => { const i = process.argv.indexOf(n); const v = i >= 0 ? parseFloat(process.argv[i + 1]) : NaN; return Number.isFinite(v) ? v : d; };
const MIN_IMPR = argVal('--min-impr', 1);

if (!fs.existsSync(IMP)) { console.error('data/gsc-page-impressions.json missing — run gsc-export-pages.cjs first'); process.exit(1); }
const data = JSON.parse(fs.readFileSync(IMP, 'utf8'));

const rows = Object.entries(data.pages || {})
  .map(([p, v]) => ({
    path: p, url: SITE + (p === '/' ? '/' : p),
    impressions: v.impressions || 0, clicks: v.clicks || 0,
    ctr: v.ctr || 0, position: v.position || 0,
  }))
  .filter((r) => r.position >= 7.5 && r.position <= 20.5 && r.impressions >= MIN_IMPR)
  // biggest impressions first = biggest click upside; tie-break by better (lower) position
  .sort((a, b) => b.impressions - a.impressions || a.position - b.position);

// a rough click-upside estimate: if moved to ~pos 4, CTR ~6% (conservative)
const estUpside = (r) => Math.round(r.impressions * 0.06);

const isTool = (p) => /^\/[a-z-]+\/[a-z0-9-]+\/?$/.test(p);
const isGuide = (p) => p.startsWith('/guides/') || p.startsWith('/blog/');

const lines = [];
lines.push('# POSITION 8–20 → TOP 5 PLAN');
lines.push('');
lines.push('> Auto-generated by `node scripts/build-pos8-20-plan.cjs` from live GSC page data.');
lines.push('> Window: ' + (data.startDate || '?') + ' → ' + (data.endDate || '?') + ' (' + (data.days || 28) + ' din). Generated ' + new Date().toISOString().slice(0, 10) + '.');
lines.push('');
lines.push('**Kyun ye list:** ye pages already **position 8–20** par hain — Google unhe page 2 par');
lines.push('rank kar raha hai. Inhe top 5 mein laana sabse sasta win hai: thoda on-page push +');
lines.push('CTR + 1–2 real backlink. Fee ki position 30–70 wale pages mehnat zyada, fayda kam.');
lines.push('');
lines.push('**' + rows.length + ' pages** position 8–20 mein hain (min ' + MIN_IMPR + ' impressions).');
lines.push('');
if (!rows.length) {
  lines.push('_Koi page 8–20 window mein nahi mila. `gsc-export-pages.cjs --days 28` dobara chalao._');
} else {
  lines.push('| # | Page | avg pos | impressions | clicks | est. clicks @ top5 |');
  lines.push('|---|---|---|---|---|---|');
  rows.forEach((r, i) => {
    lines.push('| ' + (i + 1) + ' | `' + r.path + '` | ' + r.position.toFixed(1) + ' | ' + r.impressions + ' | ' + r.clicks + ' | +' + estUpside(r) + ' |');
  });
  lines.push('');
  lines.push('## Har page par kya karo (white-hat checklist)');
  lines.push('');
  lines.push('1. **Title** — primary keyword exactly wahi jo query mein aa raha hai, 50–60 chars,');
  lines.push('   year/number hook daalein (e.g. "Free + Formula"). Current titles 30–60 gate pass karte hain.');
  lines.push('2. **Meta description** — jo dikhta hai wahi click karwata hai: benefit + "Free" + "instant".');
  lines.push('   (CTR 0.1% ka bada hissa weak snippet hai.)');
  lines.push('3. **First 100 words** — query ka jawab seedha upar, table/formula ke saath (AEO/GEO).');
  lines.push('4. **Internal links** — 2–3 relevant pages se is page ko link karo (jo already rank kar rahe hain).');
  lines.push('5. **Schema** — WebApplication + FAQPage already live; jo missing ho wo add karo.');
  lines.push('6. **Backlink** — in top pages ke liye 1 real, relevant mention (outreach) high-impact hai.');
  lines.push('');
  lines.push('## Priority order (immediate action)');
  lines.push('');
  lines.push('Pehle wo pages jinke **impressions zyada + position 8–15** hain — inse aaj hi clicks aa sakte hain:');
  lines.push('');
  rows.filter((r) => r.position <= 15).slice(0, 15).forEach((r, i) => {
    lines.push((i + 1) + '. `' + r.path + '` — pos ' + r.position.toFixed(1) + ', ' + r.impressions + ' impr');
  });
  if (!rows.some((r) => r.position <= 15)) lines.push('_(koi page position 15 se behtar nahi)_');
}
lines.push('');
lines.push('Machine-readable: `data/pos-8-20-plan.json`.');
lines.push('');

fs.writeFileSync(OUT_MD, lines.join('\n'));
fs.writeFileSync(OUT_JSON, JSON.stringify({
  ranAt: new Date().toISOString(),
  window: { start: data.startDate, end: data.endDate, days: data.days },
  count: rows.length,
  totalImpressions: rows.reduce((n, r) => n + r.impressions, 0),
  estClickUpside: rows.reduce((n, r) => n + estUpside(r), 0),
  rows,
}, null, 2));

console.log('=== Position 8–20 plan ===');
console.log(rows.length + ' pages · ' + rows.reduce((n, r) => n + r.impressions, 0) + ' impressions · est +' + rows.reduce((n, r) => n + estUpside(r), 0) + ' clicks if top-5');
for (const r of rows.slice(0, 12)) console.log('  pos ' + r.position.toFixed(1) + '  ' + String(r.impressions).padStart(4) + ' impr  ' + r.path);
console.log('💾 docs/POS-8-20-PLAN.md + data/pos-8-20-plan.json');
