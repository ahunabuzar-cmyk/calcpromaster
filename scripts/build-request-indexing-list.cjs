#!/usr/bin/env node
// ============================================================
// CalcProMaster — Build the "Request Indexing (top 40)" list
// ------------------------------------------------------------
// Google Search Console ka "Request Indexing" action sirf UI se hota hai —
// koi public API nahi. Is liye ye script data se ek PRIORITIZED list banata
// hai jise owner GSC mein ek-ek URL paste karke request kar sakta hai.
//
// Priority: (1) not-indexed pages jinko GSC impressions de raha hai
// (actual demand), (2) phir key evergreen pages (homepage, hubs, about).
//
// Input:  data/gsc-coverage-report.json (optional) + data/gsc-page-impressions.json
// Output: docs/REQUEST-INDEXING-TOP40.md
// Usage:  node scripts/build-request-indexing-list.cjs [--top 40]
// ============================================================
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://calcpromaster.com';
const COVERAGE = path.join(ROOT, 'data', 'gsc-coverage-report.json');
const IMPRESSIONS = path.join(ROOT, 'data', 'gsc-page-impressions.json');
const OUT = path.join(ROOT, 'docs', 'REQUEST-INDEXING-TOP40.md');

const arg = (n, d) => { const i = process.argv.indexOf(n); const v = i >= 0 ? parseInt(process.argv[i + 1], 10) : NaN; return Number.isFinite(v) && v > 0 ? v : d; };
const TOP = arg('--top', 40);

function stripSlash(u) { return u.replace(/\/+$/, ''); }

const imp = fs.existsSync(IMPRESSIONS) ? (JSON.parse(fs.readFileSync(IMPRESSIONS, 'utf8')).pages || {}) : {};
const notIndexed = new Set();
const indexedSet = new Set();
if (fs.existsSync(COVERAGE)) {
  const rep = JSON.parse(fs.readFileSync(COVERAGE, 'utf8'));
  for (const r of [...(rep.lists.DISCOVERED || []), ...(rep.lists.UNKNOWN || [])]) notIndexed.add(stripSlash(r.url));
  for (const r of (rep.lists.INDEXED || [])) indexedSet.add(stripSlash(r.url));
}

// Candidates = not-indexed pages with impressions (real demand), impressions desc.
const rows = Object.entries(imp)
  .map(([p, v]) => ({ path: stripSlash(p), impressions: v.impressions || 0, clicks: v.clicks || 0, position: v.position || 0 }))
  .filter((r) => notIndexed.size === 0 || notIndexed.has(r.path))
  .sort((a, b) => b.impressions - a.impressions || b.position - a.position);

const picked = rows.slice(0, TOP);
const seen = new Set(picked.map((r) => r.path));

// Fill any shortfall with key evergreen pages (homepage, hubs, trust pages).
if (picked.length < TOP) {
  const evergreen = ['/', '/about', '/editorial-policy', '/contact', '/guides/', '/graph', '/geometry-lab'];
  if (fs.existsSync(path.join(ROOT, 'sitemap.xml'))) {
    const xml = fs.readFileSync(path.join(ROOT, 'sitemap.xml'), 'utf8');
    for (const m of xml.matchAll(/\/hub\/[a-z-]+\//g)) evergreen.push(m[0]);
  }
  for (const e of evergreen) {
    if (picked.length >= TOP) break;
    const p = stripSlash(e) || '/';
    if (seen.has(p)) continue;
    if (p === '/' && (indexedSet.has('') || indexedSet.has('/'))) continue;
    // Never ask for indexing of a page Google already has: the old version of
    // this list padded itself with the homepage and every hub, all of which are
    // already "Submitted and indexed", so the owner spent quota on no-ops.
    if (indexedSet.has(p)) continue;
    seen.add(p);
    picked.push({ path: p, impressions: 0, clicks: 0, position: 0, strategic: true });
  }
}

const lines = [];
lines.push('# Request Indexing — Top ' + TOP + ' (GSC UI)');
lines.push('');
lines.push('> Auto-generated by `node scripts/build-request-indexing-list.cjs`. Generated ' + new Date().toISOString().slice(0, 10) + '.');
lines.push('>');
lines.push('> **Why manual:** Google Search Console ka "Request Indexing" action sirf UI mein hai — koi public API nahi.');
lines.push('> GSC daily quota ~10–12 requests hai, isliye list ko 3–4 din mein split karke karo.');
lines.push('>');
lines.push('> **Indexing API ka matlab?** Google ka `indexing.googleapis.com` API officially sirf');
lines.push('> **JobPosting** aur **BroadcastEvent (livestream)** pages ke liye hai. Normal calculator pages');
lines.push('> ke liye Google khud kehta hai wo support nahi karta, aur abuse par spam detection lagta hai.');
lines.push('> Is liye hum isse use NAHI karte — supported raasta: sitemap (auto-resubmitted weekly) + ye manual list.');
lines.push('');
lines.push('> Is list se aage: `node scripts/weekly-index-watcher.cjs` live URL Inspection se har URL ka');
lines.push('> current state likhta hai aur `docs/request-indexing-clickthrough.html` banata hai (one-click links).');
lines.push('');
lines.push('**Steps (ek URL ke liye):** GSC → URL Inspection (top search bar) → poora URL paste → Enter →');
lines.push('"Request Indexing" click → ~1 min wait → next URL.');
lines.push('');
lines.push('| # | URL | GSC impressions | avg pos | Note |');
lines.push('|---|---|---|---|---|');
picked.forEach((r, i) => {
  // Served URL form: tool paths end in a slash, guides/blog and one-segment
  // pages do not. The old builder appended a slash to /about and /contact,
  // which 308-redirects, so GSC reported the inspected URL as a redirect.
  const segs = r.path.split('/').filter(Boolean);
  const url = r.path === '/' ? SITE + '/'
    : r.path.startsWith('/guides/') || r.path.startsWith('/blog/') || segs.length === 1
      ? SITE + r.path
      : SITE + r.path + '/';
  const note = r.strategic ? 'evergreen/strategic' : (r.impressions >= 20 ? 'high demand' : 'demand');
  lines.push('| ' + (i + 1) + ' | ' + url + ' | ' + (r.impressions || '—') + ' | ' + (r.position ? r.position.toFixed(0) : '—') + ' | ' + note + ' |');
});
lines.push('');
lines.push('**Baad mein:** `npm run monitor:gsc` se index status dobara check karo (1–2 hafte). Pos/CTR trend `node scripts/gsc-queries.cjs --days 28` se dekho.');
lines.push('');
lines.push('_Bing/Yandex ke liye `npm run indexnow` (IndexNow) already available hai — wo supported hai._');
lines.push('');

fs.writeFileSync(OUT, lines.join('\n'));
console.log('✅ ' + picked.length + ' URLs → ' + path.relative(ROOT, OUT));
