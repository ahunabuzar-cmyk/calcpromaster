#!/usr/bin/env node
// Generate two derived snapshots from js/data/*.js (same source of truth as
// all-tool-ids.json):
//
//   js/tool-catalog.js — the lightweight search catalog (S0), all tools, sorted.
//   js/home-tools.js   — the homepage bootstrap: the FIRST N tools in the exact
//                        order js/data.js flattens CALC_DATA. The homepage shell
//                        no longer ships the four eager category chunks
//                        (see index.html "HOMEPAGE LAZY DATA"), and the only thing
//                        it needs before they arrive is tool NAMES for two
//                        below-fold blocks (Popular Tools, Most Used): this file
//                        seeds window.ALL_TOOLS / window.TOOL_MAP with those, so
//                        every existing lookup keeps working unchanged.
//
// Both are committed so tests + browser share one catalog.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'js', 'data');
const rows = [];
for (const f of fs.readdirSync(dir).filter(x => x.endsWith('.js'))) {
  const cat = f.replace('.js', '');
  const arr = require(path.join(dir, f));
  if (!Array.isArray(arr)) continue;
  for (const t of arr) {
    if (!t || !t.id || !t.name) continue;
    rows.push({
      id: t.id,
      cat,
      n: t.name,
      d: String(t.desc || '').slice(0, 90),
      k: String(t.kw || '').slice(0, 110)
    });
  }
}
rows.sort((a, b) => (a.cat + a.id).localeCompare(b.cat + b.id));

const header = `// AUTO-GENERATED by scripts/gen-tool-catalog.cjs — do not edit by hand.
// Lightweight search catalog for SmartSearch (id, category, name, desc, kw).
// Source of truth: js/data/*.js (${rows.length} tools). Regenerate after registry changes:
//   node scripts/gen-tool-catalog.cjs
window.TOOL_CATALOG = `;
const body = JSON.stringify(rows);
const footer = ';\n';

fs.writeFileSync(path.join(root, 'js', 'tool-catalog.js'), header + body + footer, 'utf8');
console.log('tool-catalog.js written:', rows.length, 'tools,', Math.round((header.length + body.length) / 1024), 'KB raw');

// ---------- js/home-tools.js ----------
// Registry order, not catalog order: js/data.js declares CALC_DATA in this exact
// key order and flattens it into ALL_TOOLS, so the first tools here are the same
// ones the pre-lazy homepage rendered for a fresh visitor. Keep that order or the
// Popular Tools block changes silently.
const CAT_ORDER = (() => {
  const src = fs.readFileSync(path.join(root, 'js', 'data.js'), 'utf8');
  const keys = [];
  const re = /^\s{2}([a-z][a-z0-9]*):\s*\{\s*name:/gm;
  let m;
  while ((m = re.exec(src))) keys.push(m[1]);
  return keys;
})();
// Mirror of the catKey → file map in js/data-loader.js (EAGER + LAZY).
const CAT_FILE = {
  finance: 'finance', health: 'health', math: 'math', everyday: 'everyday',
  science: 'science', engineering: 'engineering', construction: 'construction',
  conversion: 'conversion', business: 'business', education: 'education',
  utilities: 'utilities', lifestyle: 'lifestyle', regional: 'regional',
  food: 'food-nutrition', fitness: 'fitness-exercise', auto: 'auto-transport',
  career: 'career-freelance', homegarden: 'home-garden', tech: 'tech-digital',
  family: 'parenting-family'
};
// Two audiences, two rules — both cheap:
//  · a FRESH visitor sees the first 12 tools in registry order (the documented
//    curated fallback in renderHome), so those go in first;
//  · a RETURNING visitor's "Most Used" chips are analytics ids from ANY category,
//    so each category contributes its first PER_CAT tools — the popular heads of
//    the category (finance/loan-emi, health/bmi, …). Without this, a chip whose
//    id is not seeded is silently dropped until the real chunks land.
const TOP_N = 12;
const PER_CAT = 8;
const boot = [];
const seen = new Set();
const missing = [];
function push(key, t) {
  if (!t || !t.id || !t.name || seen.has(t.id)) return;
  seen.add(t.id);
  boot.push({ id: t.id, cat: key, name: t.name, desc: String(t.desc || '').slice(0, 120) });
}
const byCat = [];
for (const key of CAT_ORDER) {
  const file = CAT_FILE[key];
  if (!file) { missing.push(key); continue; }
  let arr;
  try { arr = require(path.join(dir, file + '.js')); } catch (e) { missing.push(key + ' (' + e.message + ')'); continue; }
  if (!Array.isArray(arr)) { missing.push(key + ' (not an array)'); continue; }
  byCat.push({ key: key, tools: arr });
}
for (const c of byCat) {
  if (boot.length >= TOP_N) break;
  for (const t of c.tools.slice(0, TOP_N)) push(c.key, t);
}
for (const c of byCat) {
  for (const t of c.tools.slice(0, PER_CAT)) push(c.key, t);
}
if (missing.length) console.warn('home-tools.js: category file(s) not resolved:', missing.join(', '));
if (!boot.length) throw new Error('home-tools.js: no tools resolved — refusing to write an empty homepage seed');

const homeHeader = `// AUTO-GENERATED by scripts/gen-tool-catalog.cjs — do not edit by hand.
// Homepage bootstrap seed (${boot.length} tools: first 12 registry-wide + first
// ${PER_CAT} of each category). The homepage shell
// ships no category data (see index.html "HOMEPAGE LAZY DATA"), so this file puts
// the first tools into the SAME ALL_TOOLS / TOOL_MAP objects js/data.js created —
// js/data.js exposes them on window, so these are aliases, not copies, and every
// existing lookup (Popular Tools, Most Used chips, search fallback) keeps working
// until the real category chunks land via js/data-loader.js (idle / first
// interaction), which rebuilds both maps from CALC_DATA and replaces these seeds.
// Regenerate after registry changes: node scripts/gen-tool-catalog.cjs
(function () {
  var seed = `;
const homeBody = JSON.stringify(boot);
const homeFooter = `;
  if (!Array.isArray(window.ALL_TOOLS) || !window.TOOL_MAP) return; // data.js missing
  for (var i = 0; i < seed.length; i++) {
    var row = seed[i];
    if (window.TOOL_MAP[row.id]) continue;   // real data already hydrated
    var tool = { id: row.id, name: row.name, desc: row.desc, cat: row.cat, _seed: true };
    window.ALL_TOOLS.push(tool);
    window.TOOL_MAP[row.id] = tool;
  }
})();
`;

fs.writeFileSync(path.join(root, 'js', 'home-tools.js'), homeHeader + homeBody + homeFooter, 'utf8');
console.log('home-tools.js written:', boot.length, 'tools (' + byCat.length + ' categories),', Math.round((homeHeader.length + homeBody.length + homeFooter.length) / 1024) + 'KB raw');
