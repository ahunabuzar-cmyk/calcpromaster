#!/usr/bin/env node
// ============================================================
// CalcProMaster — Internal link-graph audit (contextual links only)
//
// Why: every tool page carries 1,454 site-wide inlinks via the header/
// footer nav, so a raw inlink count says nothing about editorial linking.
// This audit counts ONLY the links inside the two contextual blocks:
//   • <div class="related-section">  (Similar Calculators)
//   • <div class="explain-card ..."> (seo-guide / seo-aeo / tool-enhance)
// Then it flags pages with fewer than MIN_CONTEXTUAL inbound contextual
// links and proposes specific pages that should link to them.
//
// Usage: node scripts/link-graph-audit.cjs
// Outputs: data/link-graph-audit.json + docs/INTERNAL-LINK-AUDIT.md
// ============================================================
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DEPLOY = path.join(ROOT, 'deploy');
const MIN_CONTEXTUAL = 3;

// ---------- discover tool pages ----------
// A tool page lives at deploy/<cat>/<id>/index.html. We skip hubs, long-tail
// variants (extra path depth), guides and top-level files.
const SKIP_DIRS = new Set(['js', 'css', 'fonts', 'og', 'icons', 'embed', 'docs', 'admin', 'hub', 'guides', 'blog', 'assets', 'images', 'test-results']);
const pages = [];
for (const cat of fs.readdirSync(DEPLOY, { withFileTypes: true })) {
  if (!cat.isDirectory() || SKIP_DIRS.has(cat.name)) continue;
  const catDir = path.join(DEPLOY, cat.name);
  for (const tool of fs.readdirSync(catDir, { withFileTypes: true })) {
    if (!tool.isDirectory()) continue;
    const idx = path.join(catDir, tool.name, 'index.html');
    if (!fs.existsSync(idx)) continue;
    pages.push({ cat: cat.name, id: tool.name, key: cat.name + '/' + tool.name, file: idx });
  }
}

// ---------- extract contextual link regions ----------
function contextualHrefs(html) {
  const out = new Set();
  // 1. related-section block: from its opening div to </main> (bounded)
  const rs = html.indexOf('class="related-section"');
  if (rs !== -1) {
    const end = html.indexOf('</main>', rs);
    const chunk = html.slice(rs, end === -1 ? rs + 8000 : end);
    for (const m of chunk.matchAll(/href="(\/[A-Za-z0-9-]+\/[A-Za-z0-9-]+)\/?"/g)) out.add(m[1].replace(/^\//, ''));
  }
  // 2. every explain-card block
  const cardRe = /<div class="explain-card[^"]*"[\s\S]*?<\/div>/g;
  for (const c of html.matchAll(cardRe)) {
    for (const m of c[0].matchAll(/href="(\/[A-Za-z0-9-]+\/[A-Za-z0-9-]+)\/?"/g)) out.add(m[1].replace(/^\//, ''));
  }
  return out;
}

const outLinks = new Map();   // pageKey -> Set(targetKey)
const inCount = new Map();    // targetKey -> number of contextual inbound links
const inFrom = new Map();     // targetKey -> [pageKey,...]
for (const p of pages) {
  const html = fs.readFileSync(p.file, 'utf8');
  const targets = contextualHrefs(html);
  outLinks.set(p.key, targets);
  for (const t of targets) {
    inCount.set(t, (inCount.get(t) || 0) + 1);
    if (!inFrom.has(t)) inFrom.set(t, []);
    if (inFrom.get(t).length < 8) inFrom.get(t).push(p.key);
  }
}

const known = new Set(pages.map(p => p.key));
const weak = [];
for (const p of pages) {
  const n = inCount.get(p.key) || 0;
  if (n < MIN_CONTEXTUAL) {
    // propose: same-category pages that do NOT already link here, fewest outlinks first
    const sameCat = pages.filter(q => q.cat === p.cat && q.key !== p.key && !outLinks.get(q.key).has(p.key));
    sameCat.sort((a, b) => outLinks.get(a.key).size - outLinks.get(b.key).size);
    weak.push({
      page: p.key,
      contextualInlinks: n,
      linkedFrom: inFrom.get(p.key) || [],
      suggestedLinkers: sameCat.slice(0, 3).map(q => q.key),
    });
  }
}

weak.sort((a, b) => a.contextualInlinks - b.contextualInlinks);
const result = {
  ranAt: new Date().toISOString(),
  toolPages: pages.length,
  minContextual: MIN_CONTEXTUAL,
  weakCount: weak.length,
  weak,
};

fs.writeFileSync(path.join(ROOT, 'data', 'link-graph-audit.json'), JSON.stringify(result, null, 2));

// ---------- markdown report ----------
let md = '# INTERNAL LINK AUDIT — contextual links\n\n';
md += '> Auto-generated by `node scripts/link-graph-audit.cjs`. Contextual links only\n';
md += '> (Similar Calculators + explain cards), nav/footer boilerplate excluded.\n\n';
md += 'Tool pages scanned: **' + pages.length + '**\n\n';
md += 'Pages below the ' + MIN_CONTEXTUAL + '-contextual-inlink threshold: **' + weak.length + '**\n\n';
if (weak.length) {
  md += '| Page | Contextual inlinks | Suggested linkers to add |\n|---|---|---|\n';
  for (const w of weak.slice(0, 60)) {
    md += '| /' + w.page + '/ | ' + w.contextualInlinks + ' | ' + w.suggestedLinkers.map(s => '/' + s).join(', ') + ' |\n';
  }
  if (weak.length > 60) md += '\n_…and ' + (weak.length - 60) + ' more (see data/link-graph-audit.json)._\n';
} else {
  md += 'Every tool page already meets the threshold. No action needed.\n';
}
md += '\nFull data: `data/link-graph-audit.json`.\n';
fs.writeFileSync(path.join(ROOT, 'docs', 'INTERNAL-LINK-AUDIT.md'), md);

console.log('=== Internal link-graph audit (contextual) ===');
console.log('Tool pages scanned: ' + pages.length);
console.log('Below ' + MIN_CONTEXTUAL + ' contextual inlinks: ' + weak.length);
if (weak.length) {
  console.log('\nLowest first:');
  for (const w of weak.slice(0, 15)) {
    console.log('  /' + w.page + '/  inlinks=' + w.contextualInlinks + '  -> add links from ' + w.suggestedLinkers.join(', '));
  }
}
console.log('\n💾 data/link-graph-audit.json + docs/INTERNAL-LINK-AUDIT.md');
