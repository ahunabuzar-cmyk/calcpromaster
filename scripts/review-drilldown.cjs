// Generates docs/review-drilldown-remaining.md — the full list of calculators that still
// require independent formula review (honest NEEDS HUMAN REVIEW backlog), grouped by category
// and sorted YMYL-first (health/finance/tax/family/nutrition first).
// Run: node scripts/review-drilldown.cjs
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA_DIR = path.join(ROOT, 'js', 'data');

const CAT_LABEL = {
  'auto-transport': 'Auto & Transport',
  'career-freelance': 'Career & Freelance',
  'conversion': 'Conversion',
  'food-nutrition': 'Food & Nutrition',
  'fitness-exercise': 'Fitness & Exercise',
  'home-garden': 'Home & Garden',
  'lifestyle': 'Lifestyle & Home',
  'parenting-family': 'Parenting & Family',
  'regional': 'Regional (India/PK/UAE)',
  'tech-digital': 'Tech & Digital',
  'health': 'Health & Fitness',
};
// YMYL = decisions that materially affect health/money/family
const YMYL_CATS = new Set(['health', 'food-nutrition', 'finance', 'parenting-family', 'lifestyle', 'regional', 'fitness-exercise', 'career-freelance', 'business']);

function registry() {
  const files = fs.readdirSync(DATA_DIR).filter((f) => f.endsWith('.js'));
  const tools = [];
  for (const file of files) {
    const cat = file.replace(/\.js$/, '');
    const mod = require(path.join(DATA_DIR, file));
    const arr = Array.isArray(mod) ? mod : [];
    for (const t of arr) tools.push({ ...t, category: CAT_LABEL[cat] || cat, catFile: cat });
  }
  return tools;
}

function deepQACovered() {
  const src = fs.readFileSync(path.join(ROOT, 'tests', 'unit', 'formula-qa-full.test.js'), 'utf8');
  const block = src.match(/const CASES = \[([\s\S]*?)\n\];/);
  if (!block) return new Set();
  const ids = new Set();
  for (const line of block[1].split('\n')) {
    const m = line.match(/\['([a-z0-9-]+)', '([a-z0-9-]+)'/);
    if (m) ids.add(m[2]);
  }
  return ids;
}

const tools = registry();
const covered = deepQACovered();
const remaining = tools.filter((t) => !covered.has(t.id));

// group by display category
const byCat = new Map();
for (const t of remaining) {
  if (!byCat.has(t.category)) byCat.set(t.category, []);
  byCat.get(t.category).push(t);
}
// YMYL is decided by the FILE category (catFile), not the display label.
const catFileOf = (display) => {
  for (const [f, d] of Object.entries(CAT_LABEL)) if (d === display) return f;
  return display;
};
const order = [...byCat.entries()].sort((a, b) => {
  const ymyl = (display) => (YMYL_CATS.has(catFileOf(display)) ? 0 : 1);
  const x = ymyl(a[0]), y = ymyl(b[0]);
  return x !== y ? x - y : b[1].length - a[1].length;
});

let md = `# CalcProMaster — Remaining Formula-Review Backlog (NEEDS HUMAN REVIEW)

> Generated by \`node scripts/review-drilldown.cjs\` — derived from the calculator registry
> (js/data/*.js) and the independent known-answer test suite (tests/unit/formula-qa-full.test.js).
> PASS set is computed from the test suite — never hand-edited. These calculators are
> **NOT falsely claimed as verified**; they await independent human formula review.

**Total calculators: ${tools.length}**
**Independent known-answer PASS: ${tools.length - remaining.length}**
**NEEDS HUMAN REVIEW: ${remaining.length} (${Math.round((remaining.length / tools.length) * 100)}%)**

Priority order: YMYL categories first (health, food & nutrition, finance, parenting & family,
lifestyle, regional, fitness, career, business), then non-YMYL, each sorted by size.

`;

let n = 0;
for (const [cat, list] of order) {
  const ymyl = YMYL_CATS.has(catFileOf(cat)) ? '🟥 YMYL' : '⬜';
  md += `\n## ${cat} — ${list.length} remaining ${ymyl}\n\n`;
  md += '| # | Tool ID | Route | Name |\n|---|---|---|---|\n';
  for (const t of list.sort((a, b) => a.id.localeCompare(b.id))) {
    n++;
    md += `| ${n} | \`${t.id}\` | /${t.catFile}/${t.id} | ${t.name} |\n`;
  }
}

md += `\n---\n\nTotal listed: ${n} calculators awaiting independent formula review.\n`;
fs.writeFileSync(path.join(ROOT, 'docs', 'review-drilldown-remaining.md'), md);
console.log('Remaining:', remaining.length, '| PASS:', tools.length - remaining.length, '| wrote docs/review-drilldown-remaining.md');
