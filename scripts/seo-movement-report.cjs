#!/usr/bin/env node
// ============================================================
// CalcProMaster — Dated SEO movement report (one command)
// ------------------------------------------------------------
// Sab data files + live host check se ek clean, dated Markdown report
// banata hai. Isko har hafte chalao; reports ek doosre se compare ho jayengi.
//
// Reads:  data/gsc-coverage-export-*/Chart.csv (daily series → run-rate)
//         data/gsc-queries-raw.txt · data/gsc-page-impressions.json
//         data/gsc-coverage-report.json · data/gsc-coverage-fresh.json
//         data/not-indexed-audit.json
//         data/gsc-inspect-notindexed.json · (live) check-host-redirects.cjs
// Writes: docs/SEO-MOVEMENT-<YYYY-MM-DD>.md
// Usage:  node scripts/seo-movement-report.cjs
//
// Section 1 headlines the 7-DAY RUN-RATE, not the 28-day average. During a ramp
// the 28-day average carries the pre-ramp days and reads 2-3x below the real
// speed, so leading with it made every dated report understate the site.
// ============================================================
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

// One definition of "run-rate" for every report: the growth model owns it.
const { runRate, readDailySeries, trimUnfinalized, DAYS_PER_MONTH } = require('./build-growth-model.cjs');

const ROOT = path.join(__dirname, '..');
const readJson = (p) => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8')); } catch (e) { return null; } };
const exists = (p) => fs.existsSync(path.join(ROOT, p));

const today = new Date().toISOString().slice(0, 10);
const L = [];
L.push('# CalcProMaster — SEO Movement Report');
L.push('');
L.push('**Date:** ' + today);
L.push('**Site:** https://calcpromaster.com/');
L.push('> Auto-generated by `node scripts/seo-movement-report.cjs`.');
L.push('');

// ---- 1. RUN-RATE FIRST (the headline), 28-day average below it as context ----
const num = (n, d = 0) => (Number.isFinite(n) ? n.toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d }) : '?');
// Same finality rule as the growth model and the run-rate tracker: a day GSC is
// still filling in must not be averaged into a rate (19-21 Oct read 2, 4 and 1).
const allDays = readDailySeries();
const series = trimUnfinalized(allDays, 3);
const droppedDays = allDays.length - series.length;
const rr7 = runRate(series, 7);
const rr3 = runRate(series, 3);
// The raw dump's 28-day totals, kept for clicks/position/CTR which the daily
// impressions series does not carry.
let raw28 = null;
if (exists('data/gsc-queries-raw.txt')) {
  const m = fs.readFileSync(path.join(ROOT, 'data/gsc-queries-raw.txt'), 'utf8')
    .match(/clicks=(\d+)\s+impressions=(\d+)\s+ctr=([\d.]+)%\s+pos=([\d.]+)/);
  if (m) raw28 = { clicks: +m[1], impressions: +m[2], ctr: m[3], position: m[4] };
}

L.push('## 1. Run-rate (headline)');
L.push('');
if (rr7) {
  L.push('- **7-day run-rate: ' + num(rr7.perDay) + ' impressions/day ≈ ' + num(rr7.perMonth) + '/month** (' + rr7.from + ' → ' + rr7.to + ')');
  if (rr3) L.push('- 3-day: ' + num(rr3.perDay) + '/day ≈ ' + num(rr3.perMonth) + '/month (' + rr3.from + ' → ' + rr3.to + ')');
  if (droppedDays > 0) L.push('- Excluded: last ' + droppedDays + ' day(s) of the chart are not finalised by GSC yet (raw export ends ' + allDays[allDays.length - 1].date + ').');
} else {
  L.push('- _(daily series nahi mili — GSC se Coverage export lein aur `node scripts/parse-gsc-coverage-export.cjs --dir <folder>` chalao)_');
}
// The 28-day average is taken from the SAME series as the run-rate, so the two
// numbers cover one window and can be compared honestly. data/gsc-queries-raw.txt
// used to supply it, but its window is whatever day the API was last called —
// comparing that to a chart that has moved on is how "impressions fell" was
// concluded from two different periods.
const rr28 = runRate(series, 28);
if (rr28) {
  L.push('- trailing ' + rr28.days + '-day average: ' + num(rr28.perDay) + '/day ≈ ' + num(rr28.perMonth) + '/month (' + rr28.from + ' → ' + rr28.to + ') — **lagging number**, ramp ke pehle wale din isi mein shamil hain' + (rr7 ? ' (' + (rr7.perDay / rr28.perDay).toFixed(1) + 'x run-rate se)' : ''));
}
if (raw28) {
  L.push('- Clicks (API, last 28 days at pull time): **' + raw28.clicks + '** · CTR **' + raw28.ctr + '%** · avg position **' + raw28.position + '**');
}
L.push('');
L.push('_Run-rate ke liye 7-day window padho. 28-day average ko speed na samjho — wo trend comparison ka number hai._');
L.push('');
L.push('> `node scripts/run-rate-tracker.cjs` is number ko history mein jama karta hai aur 2 hafte ka stall detect karta hai.');
L.push('');

// ---- 2. per-page impressions ----
const imp = readJson('data/gsc-page-impressions.json');
L.push('## 2. Pages earning impressions');
L.push('');
if (imp && imp.pages) {
  const pages = Object.entries(imp.pages);
  L.push('- **' + pages.length + ' pages** ko impressions mile (' + (imp.startDate || '?') + ' → ' + (imp.endDate || '?') + ').');
  const top = pages.sort((a, b) => (b[1].impressions || 0) - (a[1].impressions || 0)).slice(0, 8);
  L.push('');
  L.push('| Impressions | Clicks | Avg pos | Page |');
  L.push('|---|---|---|---|');
  for (const [p, v] of top) L.push('| ' + (v.impressions || 0) + ' | ' + (v.clicks || 0) + ' | ' + (v.position || 0) + ' | `' + p + '` |');
} else L.push('- _(data/gsc-page-impressions.json missing)_');
L.push('');

// ---- 3. coverage snapshot ----
const cov = readJson('data/gsc-coverage-report.json');
L.push('## 3. Google indexation (coverage)');
L.push('');
if (cov && cov.tally) {
  L.push('- Snapshot: **' + String(cov.ranAt).slice(0, 10) + '** · ' + cov.uniqueUrls + ' URLs inspected.');
  L.push('');
  L.push('| Verdict | Count |');
  L.push('|---|---|');
  for (const [k, v] of Object.entries(cov.tally).sort((a, b) => b[1] - a[1])) L.push('| ' + k + ' | ' + v + ' |');
  const ni = (cov.lists.DISCOVERED || []).length + (cov.lists.UNKNOWN || []).length;
  L.push('');
  L.push('- **Not indexed (Discovered + Unknown): ' + ni + '.**');
} else L.push('- _(data/gsc-coverage-report.json missing)_');
L.push('');

// ---- 3b. fresh GSC Coverage UI export (site-wide truth, UI-only source) ----
const fresh = readJson('data/gsc-coverage-fresh.json');
L.push('## 3b. Google indexation — fresh GSC Coverage export');
L.push('');
if (fresh && fresh.issues) {
  const L0 = fresh.latest || null;
  if (L0) {
    const tot = (L0.indexed || 0) + (L0.notIndexed || 0);
    L.push('- Snapshot **' + L0.date + '**: Indexed **' + L0.indexed + '** · Not indexed **' + L0.notIndexed + '** · ' + (tot ? (100 * L0.indexed / tot).toFixed(1) : '?') + '% indexed.');
    L.push('');
  }
  L.push('| Reason | Source | Pages |');
  L.push('|---|---|---|');
  for (const i of [...fresh.issues].sort((a, b) => b.pages - a.pages)) L.push('| ' + i.reason + ' | ' + i.source + ' | ' + i.pages + ' |');
  const t = fresh.totals || {};
  L.push('');
  L.push('- Website-side faults: **' + (t.websiteFaults || 0) + '** · Google-systems side: **' + (t.googleSystems || 0) + '**.');
  L.push('- _Ye GSC Coverage UI export (UI-only, koi public API nahi) se aata hai — ZIP kholo aur `node scripts/parse-gsc-coverage-export.cjs --dir <folder>` chalao._');
} else L.push('- _(data/gsc-coverage-fresh.json missing — GSC ZIP export kholo aur `node scripts/parse-gsc-coverage-export.cjs --dir <folder>` chalao)_');
L.push('');

// ---- 4. live inspection progress ----
const insp = readJson('data/gsc-inspect-notindexed.json');
L.push('## 4. Live URL-Inspection (not-indexed set)');
L.push('');
if (insp && insp.results) {
  const t = {};
  for (const r of insp.results) t[r.coverage] = (t[r.coverage] || 0) + 1;
  const indexed = t['Submitted and indexed'] || 0;
  L.push('- Inspected **' + insp.results.length + '/' + (insp.total || '?') + '** · now indexed **' + indexed + '** (' + Math.round(100 * indexed / insp.results.length) + '%).');
  L.push('');
  L.push('| Coverage state | Count |');
  L.push('|---|---|');
  for (const [k, v] of Object.entries(t).sort((a, b) => b[1] - a[1])) L.push('| ' + k + ' | ' + v + ' |');
} else L.push('- _(data/gsc-inspect-notindexed.json missing — `node scripts/gsc-inspect-list.cjs` chalao)_');
L.push('');

// ---- 5. not-indexed audit ----
const audit = readJson('data/not-indexed-audit.json');
L.push('## 5. Not-indexed full audit');
L.push('');
if (audit) {
  L.push('- Audited **' + audit.notIndexedTotal + '** not-indexed pages.');
  L.push('- **Fixable blockers: ' + audit.fixable + '** · waiting on crawl: **' + audit.waitingCrawl + '**.');
  if (audit.fixable === 0) L.push('- ✅ Koi technical blocker nahi — sab clean, sirf index/crawl baaki.');
} else L.push('- _(data/not-indexed-audit.json missing — `node scripts/audit-not-indexed.cjs` chalao)_');
L.push('');

// ---- 6. host check (live) ----
L.push('## 6. Host consolidation (live)');
L.push('');
try {
  const out = execFileSync(process.execPath, [path.join(ROOT, 'scripts', 'check-host-redirects.cjs'), '--json'], { cwd: ROOT, encoding: 'utf8', timeout: 60000 });
  const j = JSON.parse(out);
  L.push('- Result: **' + (j.pass ? '✅ PASS' : '❌ FAIL') + '** (' + j.origin + ')');
  L.push('');
  L.push('| Probe | Expect | Actual | Status |');
  L.push('|---|---|---|---|');
  for (const p of j.probes) L.push('| ' + p.name + ' | ' + p.expect + ' | ' + (p.status || '—') + (p.location ? ' → ' + p.location : '') + ' | ' + (p.ok ? '✅' : '❌') + ' |');
} catch (e) {
  L.push('- ⚠ Host check nahi chal paaya (network?). `node scripts/check-host-redirects.cjs` manually chalao.');
}
L.push('');

// ---- 7. tomorrow/next steps ----
L.push('## 7. Aage kya');
L.push('');
L.push('1. GSC → Request Indexing (`docs/REQUEST-INDEXING-TOP40.md`) — ~12 URLs/din.');
L.push('2. Backlinks (off-page) — authority badhao (white-hat only).');
L.push('3. `node scripts/gsc-inspect-list.cjs --limit 300` se baaki not-indexed set check karo (resumable).');
L.push('4. `node scripts/build-pos8-20-plan.cjs` wale top pages par on-page push karo.');
L.push('');

const outName = 'docs/SEO-MOVEMENT-' + today + '.md';
fs.writeFileSync(path.join(ROOT, outName), L.join('\n'));
console.log('✅ ' + outName);
