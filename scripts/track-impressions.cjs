#!/usr/bin/env node
// ====== CalcProMaster — Impressions Tracker (GSC API) ======
// Pulls REAL 7-day performance from Google Search Console and writes a readable
// progress report: docs/IMPRESSION-TRACKER.md  (run-rate, page-2 quick wins,
// and progress towards the 200k/month and 1M/month goals).
//
// Zero new dependencies — reuses scripts/lib/google-oauth.cjs (the same refresh
// token the other GSC scripts use).
//
// Usage:
//   node scripts/track-impressions.cjs            # fetch + write report
//   node scripts/track-impressions.cjs --days 28  # use a wider window
'use strict';
const https = require('https');
const fs = require('fs');
const path = require('path');
const { getAccessToken } = require('./lib/google-oauth.cjs');

const GOAL_MONTH = 200000; // month-1 target
const GOAL_FINAL = 1000000; // long-term target
const READ_SCOPE = 'https://www.googleapis.com/auth/webmasters.readonly';

const arg = (name, dflt) => {
  const i = process.argv.indexOf(name);
  const v = i >= 0 ? parseInt(process.argv[i + 1], 10) : NaN;
  return Number.isFinite(v) && v > 0 ? v : dflt;
};
const DAYS = arg('--days', 7);

function readSite() {
  if (process.env.GSC_SITE_URL) return process.env.GSC_SITE_URL.replace(/\/+$/, '');
  try {
    const cfg = fs.readFileSync(path.join(__dirname, '..', 'js', 'site-config.js'), 'utf8');
    const m = cfg.match(/domain:\s*'([^']+)'/);
    if (m) return 'https://' + m[1];
  } catch (e) { /* fall through */ }
  return 'https://calcpromaster.com';
}
const SITE = readSite();

function gsc(body, token) {
  return new Promise((resolve, reject) => {
    const payload = JSON.stringify(body);
    const req = https.request({
      hostname: 'searchconsole.googleapis.com',
      path: '/webmasters/v3/sites/' + encodeURIComponent(SITE) + '/searchAnalytics/query',
      method: 'POST',
      headers: {
        Authorization: 'Bearer ' + token,
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(payload)
      }
    }, res => {
      let d = '';
      res.on('data', c => (d += c));
      res.on('end', () => {
        if (res.statusCode >= 400) return reject(new Error('HTTP ' + res.statusCode + ': ' + d.slice(0, 200)));
        resolve(JSON.parse(d || '{}'));
      });
    });
    req.on('error', reject);
    req.write(payload);
    req.end();
  });
}

function isoDaysAgo(n) {
  return new Date(Date.now() - n * 86400000).toISOString().slice(0, 10);
}

(async () => {
  const tokRes = await getAccessToken(READ_SCOPE);
  const token = typeof tokRes === 'object' && tokRes !== null ? tokRes.access_token : tokRes;

  const end = isoDaysAgo(1);
  const start = isoDaysAgo(DAYS);
  const windowDays = DAYS;

  const totalsRes = await gsc({ startDate: start, endDate: end, dataState: 'all' }, token);
  const t = (totalsRes.rows && totalsRes.rows[0]) || { clicks: 0, impressions: 0, ctr: 0, position: 0 };

  const pagesRes = await gsc({
    startDate: start, endDate: end, dimensions: ['page'], rowLimit: 250, dataState: 'all'
  }, token);
  const pages = pagesRes.rows || [];

  const perDay = t.impressions / windowDays;
  const monthly = Math.round(perDay * 30);
  const pctMonth = ((monthly / GOAL_MONTH) * 100).toFixed(1);
  const pctFinal = ((monthly / GOAL_FINAL) * 100).toFixed(1);

  // Page-2 quick wins: position 8-20 = one nudge from page 1
  const page2 = pages
    .filter(r => r.position > 7 && r.position <= 20)
    .sort((a, b) => b.impressions - a.impressions)
    .slice(0, 20);

  const page1 = pages.filter(r => r.position <= 10).length;

  const L = [];
  L.push('# IMPRESSION TRACKER — calcpromaster.com');
  L.push('');
  L.push('> Auto-generated by `node scripts/track-impressions.cjs` (real GSC data, no guesses).');
  L.push('> **Window:** last ' + windowDays + ' days (' + start + ' → ' + end + ')');
  L.push('');
  L.push('## Run-rate');
  L.push('');
  L.push('| Metric | Value |');
  L.push('|---|---|');
  L.push('| Impressions (' + windowDays + 'd) | ' + t.impressions + ' |');
  L.push('| Clicks | ' + t.clicks + ' |');
  L.push('| CTR | ' + ((t.ctr || 0) * 100).toFixed(2) + '% |');
  L.push('| Avg position | ' + (t.position || 0).toFixed(1) + ' |');
  L.push('| Impressions / day | ' + perDay.toFixed(0) + ' |');
  L.push('| **Monthly run-rate** | **~' + monthly.toLocaleString() + '** |');
  L.push('');
  L.push('## Goal progress');
  L.push('');
  L.push('| Goal | Progress |');
  L.push('|---|---|');
  L.push('| 200,000 / month | ' + pctMonth + '% |');
  L.push('| 1,000,000 / month | ' + pctFinal + '% |');
  L.push('');
  L.push('## Page-1 pages (top 10)');
  L.push('');
  L.push('**' + page1 + '** pages are already on page 1 for at least one query.');
  L.push('');
  L.push('## FASTEST WINS — page 2 (pos 8–20, one nudge from page 1)');
  L.push('');
  L.push('| # | Page | Pos | Impr |');
  L.push('|---|---|---|---|');
  page2.forEach((r, i) => {
    L.push('| ' + (i + 1) + ' | ' + r.keys[0].replace('https://calcpromaster.com', '') + ' | ' + r.position.toFixed(1) + ' | ' + r.impressions + ' |');
  });
  L.push('');
  L.push('_Next: upgrade these pages (FAQ + table + worked example + internal links) to push them to page 1._');
  L.push('');

  const out = path.join(__dirname, '..', 'docs', 'IMPRESSION-TRACKER.md');
  fs.writeFileSync(out, L.join('\n'), 'utf8');
  console.log('Wrote ' + out);
  console.log('Monthly run-rate: ~' + monthly.toLocaleString() + ' (' + pctMonth + '% of 200k) · page-2 targets: ' + page2.length);
})().catch(e => { console.error('track-impressions failed:', e.message); process.exit(1); });
